const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../utils/businessTimings.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const { timeInMinutes: parse, validateBreakTimes: validate } = context.exports;
assert.equal(parse('12:00 AM'), 0);
assert.equal(parse('12:00 PM'), 720);
assert.equal(parse('23:15:00'), 1395);
for (const invalid of ['24:00', '13:00 PM', '10:60 AM', 'n/a']) assert.equal(parse(invalid), null);
const valid = (...times) => assert.equal(Object.keys(validate(...times)).length, 0);
const invalid = (...times) => assert.ok(Object.keys(validate(...times)).length > 0);
valid('', '', '', '');
valid('09:00 AM', '09:00 PM', '', '');
valid('09:00 AM', '09:00 PM', '01:00 PM', '02:00 PM');
invalid('09:00 AM', '09:00 PM', '08:00 AM', '10:00 AM');
invalid('09:00 AM', '09:00 PM', '08:00 PM', '10:00 PM');
invalid('09:00 AM', '09:00 PM', '02:00 PM', '01:00 PM');
invalid('09:00 AM', '09:00 PM', '01:00 PM', '01:00 PM');
invalid('09:00 AM', '09:00 PM', '09:00 AM', '10:00 AM');
invalid('09:00 AM', '09:00 PM', '08:00 PM', '09:00 PM');
invalid('', '', '01:00 PM', '02:00 PM');
invalid('09:00 AM', '09:00 PM', '01:00 PM', '');
// Changing opening hours invalidates an existing break immediately.
invalid('02:00 PM', '09:00 PM', '01:00 PM', '03:00 PM');
valid('08:00 PM', '06:00 AM', '11:00 PM', '01:00 AM');
valid('08:00 PM', '06:00 AM', '01:00 AM', '02:00 AM');
invalid('08:00 PM', '06:00 AM', '01:00 PM', '02:00 PM');
invalid('08:00 PM', '06:00 AM', '02:00 AM', '01:00 AM');
console.log('Merchant break time validation: business boundaries, order, changed hours, incomplete times, noon/midnight and overnight hours passed.');
