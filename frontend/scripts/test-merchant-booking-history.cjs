const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
let calls = [], failDay = '', allUnsupported = false, inFlight = 0, peak = 0;
const slotRequest = async (url, token) => {
  calls.push({ url, token }); inFlight++; peak = Math.max(peak, inFlight);
  await new Promise(resolve => setImmediate(resolve)); inFlight--;
  const date = url.split('date=')[1];
  if (date === failDay || (!date && allUnsupported)) throw Object.assign(new Error('Unavailable'), { status: 400 });
  return date ? [{ bookingId: date, bookingDate: date, startTime: '10:00' }] : [{ bookingId: 'old', bookingDate: '2024-01-01', startTime: '10:00', status: 'CANCELLED' }, { bookingId: 'new', bookingDate: '2026-11-16', startTime: '09:00', status: 'COMPLETED' }, { bookingId: 'upcoming', bookingDate: '2026-11-23', startTime: '11:00', status: 'ACCEPTED' }];
};
const scope = { exports: {}, require: () => ({ bookingToday: () => '2026-11-16', slotRequest }) };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../utils/merchantBookingHistory.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, scope);
const { merchantBookingRange: range, rangeDates, loadMerchantBookings: load } = scope.exports;
(async () => {
  assert.equal(JSON.stringify(range('Week', '', '2026-11-16')), JSON.stringify({ start: '2026-11-16', end: '2026-11-22' }));
  assert.equal(range('Week', '', '2026-11-22').start, '2026-11-16');
  assert.equal(range('Week', '', '2027-01-01').start, '2026-12-28');
  assert.equal(range('Month', '', '2024-02-20').end, '2024-02-29');
  assert.equal(range('Month', '', '2026-02-20').end, '2026-02-28');
  assert.equal(range('Month', '', '2026-12-20').end, '2026-12-31');
  assert.equal(rangeDates('2024-02-01', '2024-02-29').length, 29);
  let records = await load('42', 'token', 'Week', '2026-11-16');
  assert.equal(records.length, 7); assert.equal(calls.length, 7); assert.ok(peak <= 4);
  assert.equal(records[0].bookingDate, '2026-11-22');
  calls = []; records = await load('42', 'token', 'Month', '2026-11-16');
  assert.equal(records.length, 30); assert.equal(calls.length, 30);
  calls = []; records = await load('42', 'token', 'All', '2026-11-16');
  assert.equal(calls[0].url, '/merchant/42/history'); assert.equal(records.length, 3); assert.equal(records[2].bookingDate, '2024-01-01');
  assert.equal(records.map(b => b.status).join(','), 'ACCEPTED,COMPLETED,CANCELLED', 'All History must preserve upcoming, completed, and cancelled bookings across dates');
  assert.ok(!calls[0].url.includes('date='), 'All History must never use the daily date filter');
  allUnsupported = true;
  await assert.rejects(load('42', 'token', 'All', ''), /All booking history needs a booking-service update/);
  failDay = '2026-11-17';
  await assert.rejects(load('42', 'token', 'Week', ''), /Unavailable/);
  calls = []; await load('42', 'token', 'Week', '', () => false); assert.equal(calls.length, 0);
  console.log('Merchant booking history checks passed: calendar weeks, month/year boundaries, leap years, complete daily aggregation, concurrency limit, all-history request, sorting, failures and stale requests.');
})().catch(error => { console.error(error); process.exitCode = 1; });
